//! The definitions file of mission source for luau-lsp, `docs/guide/mission.d.luau`
//! ([Editors](../../../../docs/formats/mission-source.md#editors)): the source's own words and the
//! types they take and give (`language`), the game's commands from its catalogue with the
//! developers' descriptions, and the names of the game's values (`vocabulary`), which editors
//! complete and describe. `sltool dte definitions` writes it, and tests check the copy in
//! `docs/guide`.

const std = @import("std");
const Allocator = std.mem.Allocator;
const Writer = std.Io.Writer;

const dte = @import("../../dte.zig");
const commands = @import("../../../engine/game/executor/commands.zig");
const conditions = @import("../../../engine/vm/conditions.zig");
const vm = @import("../../../engine/vm.zig");
const language = @import("language.zig");
const names = @import("names.zig");
const script = @import("script.zig");
const vocabulary = @import("vocabulary.zig");

pub const Error = Allocator.Error || Writer.Error;

/// Writes the definitions file, with `arena` for the names it makes.
pub fn write(arena: Allocator, w: *Writer) Error!void {
    try w.writeAll(
        \\-- The definitions of mission source for Luau's language server (luau-lsp): its declarations,
        \\-- the functions and values of its script, the game's commands and the names of the game's
        \\-- values. Add this file to the luau-lsp.types.definitionFiles setting under a name, such as
        \\-- "@mission", and turn on Luau's new type solver (luau-lsp.fflags.enableNewSolver).
        \\-- Generated by `sltool dte definitions` from the game's tables; don't change it by hand.
        \\
        \\-- The names of the game's values, as the scripting API names them. A value without a name,
        \\-- such as a mod's ship type, is a number.
        \\
        \\
    );
    inline for (comptime std.enums.values(vocabulary.Kind)) |kind| {
        if (comptime vocabulary.Names(kind)) |Enum| {
            const article = if (std.mem.findScalar(u8, "aeiou", kind.noun()[0]) != null) "An" else "A";
            try w.print("--- {s} {s}, by its name, or by its number where the game doesn't name it.\n", .{ article, kind.noun() });
            try writeNames(w, comptime typeName(kind), @typeInfo(Enum).@"enum".field_names);
        }
    }
    try w.writeAll("--- The wing a flight group's ships are listed in.\n");
    try writeNames(w, "Wing", @typeInfo(dte.FlightGroup.Wing).@"enum".field_names);
    try writeEventValues(arena, w);

    try w.writeAll("\n-- The records a mission declares, and the other types its words take and give.\n\n");
    for (language.types) |declared| {
        try w.print("--- {s}\n", .{declared.about});
        switch (declared.definition) {
            .own => |body| if (body.len == 0)
                try w.print("declare extern type {s} with end\n", .{declared.name})
            else
                try w.print("declare extern type {s} with\n    {s}\nend\n", .{ declared.name, body }),
            .alias => |definition| try w.print("export type {s} = {s}\n", .{ declared.name, definition }),
        }
    }
    try writeGameVariables(w);

    try w.writeAll("\n-- The tables of fields the declarations take.\n\n");
    for (language.tables) |table| {
        try w.print("export type {s} = {{\n", .{table.name});
        for (table.fields) |field| try w.print("    --- {s}\n    {s}: {s},\n", .{ field.about, field.name, field.type });
        if (table.events) try writeEventFields(arena, w);
        try w.writeAll("}\n");
    }

    try w.writeAll("\n-- The source's own words: its declarations, and the functions and values of its script.\n\n");
    for (std.enums.values(names.Word)) |word| {
        const declared = language.declaration(word);
        try w.print("--- {s}\n", .{declared.about});
        if (declared.parameters) |parameters| {
            try w.print("declare function {t}{s}({s}): {s}\n", .{ word, declared.generics, parameters, declared.result });
        } else {
            try w.print("declare {t}: {s}\n", .{ word, declared.result });
        }
    }

    try w.writeAll(
        \\
        \\-- The game's commands, from its catalogue. Their names, their parameters' labels and their
        \\-- descriptions are the developers' own. A command the catalogue doesn't have runs as
        \\-- `command(number, ...)`.
        \\
        \\
    );
    for (commands.table) |command| try writeCommand(arena, w, command);
}

/// The name the definitions give the type of `kind`'s values: its noun in Pascal case, such as
/// `ShipType` for a ship type.
fn typeName(comptime kind: vocabulary.Kind) []const u8 {
    comptime {
        var text: []const u8 = "";
        var upper = true;
        for (kind.noun()) |char| {
            if (char == ' ') {
                upper = true;
                continue;
            }
            text = text ++ .{if (upper) std.ascii.toUpper(char) else char};
            upper = false;
        }
        return text;
    }
}

/// Writes the type `name`: the names `tags` give, but placeholders such as `_unused_2`, or a number
/// for a value without a name.
fn writeNames(w: *Writer, name: []const u8, tags: []const [:0]const u8) Writer.Error!void {
    try w.print("export type {s} = ", .{name});
    for (tags) |tag| {
        if (tag[0] != '_') try w.print("\"{s}\" | ", .{tag});
    }
    try w.writeAll("number\n");
}

/// Writes `EventValue`, which `last_event` takes: the value of a condition's event by its label in
/// the condition catalogue, or by its place.
fn writeEventValues(arena: Allocator, w: *Writer) Error!void {
    var labels: std.StringArrayHashMapUnmanaged(void) = .empty;
    for (conditions.table) |condition| {
        for (condition.values) |value| try labels.put(arena, value.label, {});
    }
    try w.writeAll("--- A value of a condition's event, by its label in the condition catalogue, or by its place.\nexport type EventValue = ");
    for (labels.keys()) |label| try w.print("\"{s}\" | ", .{label});
    try w.writeAll("number\n");
}

/// Writes `GameVariables`, the type of `game`: each of the game's variables that has a name, and
/// the rest by their numbers.
fn writeGameVariables(w: *Writer) Writer.Error!void {
    try w.writeAll("--- The game's variables, which `game` holds.\nexport type GameVariables = {\n");
    for (@typeInfo(vm.GameVariable).@"enum".field_names) |name| {
        if (vocabulary.variableNumber(name) != null) try w.print("    {s}: number,\n", .{name});
    }
    try w.writeAll("    [number]: number,\n}\n");
}

/// Writes the fields of a trigger's table for the values of its condition's events that it checks:
/// each by the name the trigger's function gives it, with the conditions whose events carry it.
fn writeEventFields(arena: Allocator, w: *Writer) Error!void {
    const Checked = struct {
        label: []const u8,
        /// Whether it's a number rather than a ship, a flight group or a squad.
        number: bool,
        conditions: std.ArrayList([]const u8) = .empty,
    };
    var found: std.StringArrayHashMapUnmanaged(Checked) = .empty;
    for (conditions.table, 0..) |condition, number| {
        const event = try script.eventNames(arena, condition.values);
        const condition_name = vocabulary.name(.condition, @intCast(number)) orelse try std.fmt.allocPrint(arena, "{d}", .{number});
        for (condition.values, event) |value, name| {
            if (!value.checked) continue;
            const slot = try found.getOrPut(arena, name);
            if (!slot.found_existing) slot.value_ptr.* = .{ .label = value.label, .number = value.kinds.number or value.kinds.constant };
            try slot.value_ptr.conditions.append(arena, condition_name);
        }
    }
    for (found.keys(), found.values()) |name, checked| {
        const what = if (checked.number) "a number" else "a ship, a flight group, a squad or `any_ship`";
        try w.print("    --- What the event's \"{s}\" must be for the trigger to fire: {s}. In triggers of ", .{ checked.label, what });
        for (checked.conditions.items, 0..) |condition, index| {
            const separator = if (index == 0) "" else if (index + 1 == checked.conditions.items.len) " and " else ", ";
            try w.print("{s}`{s}`", .{ separator, condition });
        }
        try w.print(".\n    {s}: {s},\n", .{ name, if (checked.number) "number?" else "(Entity | number)?" });
    }
}

/// Writes `command`'s declaration, with its description and its parameters' labels.
fn writeCommand(arena: Allocator, w: *Writer, command: commands.Command) Error!void {
    var namer: names.Namer = .init(arena);
    const parameters = try arena.alloc([]const u8, command.params.len);
    for (parameters, command.params, 0..) |*name, param, index| name.* = try namer.name(labelHead(param.label), "param", index);
    if (command.description.len > 0) try w.print("--- {s}\n", .{command.description});
    for (parameters, command.params) |name, param| try w.print("--- @param {s} -- {s}\n", .{ name, param.label });
    try w.print("declare function {s}(", .{command.name});
    for (parameters, command.params, 0..) |name, param, index| {
        try w.print("{s}{s}: {f}", .{ if (index == 0) "" else ", ", name, ParameterType{ .param = param } });
    }
    try w.writeAll("): ()\n");
}

/// What a parameter's name is made from: its label up to the first bracket, comma or semicolon,
/// which start a note, such as "(can be NULL)".
fn labelHead(label: []const u8) []const u8 {
    const end = std.mem.findAny(u8, label, "(,;") orelse label.len;
    return std.mem.trim(u8, label[0..end], " ");
}

/// The type of a command's parameter: each kind of value it takes, or a value of a kind the game
/// names, such as an order. A parameter that can be null is optional.
const ParameterType = struct {
    param: commands.Param,

    pub fn format(shown: ParameterType, w: *Writer) Writer.Error!void {
        const kinds = shown.param.kinds;
        // The three kinds of record, a curve, a value and text.
        var buffer: [6][]const u8 = undefined;
        var list: std.ArrayList([]const u8) = .initBuffer(&buffer);
        if (kinds.ship and kinds.flight_group and kinds.squad) {
            list.appendAssumeCapacity("Entity");
        } else inline for (.{ .{ "ship", "Ship" }, .{ "flight_group", "FlightGroup" }, .{ "squad", "Squad" } }) |pair| {
            if (@field(kinds, pair[0])) list.appendAssumeCapacity(pair[1]);
        }
        if (kinds.curve) list.appendAssumeCapacity("Curve");
        if (vocabulary.of(shown.param)) |kind| {
            list.appendAssumeCapacity(switch (kind) {
                .part => "Part",
                inline else => |known| comptime typeName(known),
            });
        } else if (kinds.number or kinds.constant or kinds.percentage) {
            list.appendAssumeCapacity("number");
        }
        if (kinds.file_name or kinds.text) list.appendAssumeCapacity("string");
        if (list.items.len == 0) return w.writeAll("any");
        const several = list.items.len > 1 and shown.param.extra.nullable;
        if (several) try w.writeByte('(');
        for (list.items, 0..) |name, index| try w.print("{s}{s}", .{ if (index == 0) "" else " | ", name });
        if (several) try w.writeByte(')');
        if (shown.param.extra.nullable) try w.writeByte('?');
    }
};

test "the definitions don't change unless the game's tables or the source do" {
    var arena_state: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena_state.deinit();
    var out: Writer.Allocating = .init(arena_state.allocator());
    try write(arena_state.allocator(), &out.writer);
    if (!std.mem.eql(u8, out.written(), @embedFile("mission.d.luau"))) {
        std.debug.print("the definitions of mission source have changed: if that's meant, run `make definitions` to update docs/guide/mission.d.luau\n", .{});
        return error.TestUnexpectedResult;
    }
}

test labelHead {
    try std.testing.expectEqualStrings("Entity to target", labelHead("Entity to target (can be NULL)"));
    try std.testing.expectEqualStrings("TRUE for enable", labelHead("TRUE for enable; FALSE for disable"));
    try std.testing.expectEqualStrings("true - object targetable", labelHead("true - object targetable, false - not targetable"));
    try std.testing.expectEqualStrings("Probability of Nanny Rescue", labelHead("Probability of Nanny Rescue    ( 1-100% )"));
    try std.testing.expectEqualStrings("AI Mode", labelHead("AI Mode"));
}

test write {
    var arena_state: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();
    var out: Writer.Allocating = .init(arena);
    try write(arena, &out.writer);
    const text = out.written();

    // A command's parameters are named after their labels, and typed by what they take: SetAI
    // takes an order by its name, and a target that can be nil.
    try std.testing.expect(std.mem.find(u8, text,
        \\--- Sets a Ship or Flight Group's AI pattern
        \\--- @param entity_to_be_controlled -- Entity to be controlled
        \\--- @param ai_mode -- AI Mode
        \\--- @param initialize_immediately -- Initialize Immediately (T/F)
        \\--- @param entity_to_target -- Entity to target (can be NULL)
        \\declare function SetAI(entity_to_be_controlled: Entity, ai_mode: Order, initialize_immediately: number, entity_to_target: Entity?): ()
    ) != null);
    // The values a trigger checks are fields of its table.
    try std.testing.expect(std.mem.find(u8, text, "    attacker: (Entity | number)?,\n") != null);

    // Every type the file uses, it declares. A capitalised name outside the comments and the
    // strings is a type, but for the commands' names and the type parameters, such as `A`.
    var declared: std.StringHashMapUnmanaged(void) = .empty;
    var lines = std.mem.splitScalar(u8, text, '\n');
    while (lines.next()) |line| {
        for ([_][]const u8{ "export type ", "declare extern type " }) |prefix| {
            const rest = std.mem.cutPrefix(u8, line, prefix) orelse continue;
            try declared.put(arena, rest[0 .. std.mem.findAny(u8, rest, " =") orelse rest.len], {});
        }
    }
    lines = std.mem.splitScalar(u8, text, '\n');
    while (lines.next()) |line| {
        if (std.mem.startsWith(u8, std.mem.trimStart(u8, line, " "), "--")) continue;
        const code = if (std.mem.cutPrefix(u8, line, "declare function ")) |rest| rest[std.mem.findAny(u8, rest, "(<").?..] else line;
        var quoted = false;
        var start: ?usize = null;
        for (code, 0..) |char, at| {
            if (char == '"') quoted = !quoted;
            const part_of_name = std.ascii.isAlphanumeric(char) or char == '_';
            if (part_of_name and start == null and !quoted) start = at;
            if (!part_of_name or at + 1 == code.len) if (start) |first| {
                const end = if (part_of_name) at + 1 else at;
                const name = code[first..end];
                start = null;
                if (!std.ascii.isUpper(name[0]) or name.len == 1) continue;
                if (!declared.contains(name)) {
                    std.debug.print("the definitions use {s}, which they don't declare: {s}\n", .{ name, line });
                    return error.TestUnexpectedResult;
                }
            };
        }
    }
}
